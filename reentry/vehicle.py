"""Параметры объекта и начальные условия входа."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .constants import OMEGA_EARTH, R_EARTH


@dataclass
class Vehicle:
    """Входящий объект.

    Шаг 1: масса постоянна. На шаге 4 она станет переменной состояния,
    и ballistic_coefficient начнёт дрейфовать по ходу полёта.

    Cd: на 120-90 км течение свободномолекулярное (Kn >> 1), для выпуклого
        тела с диффузным отражением Cd ~ 2.0-2.2. Ниже ~70 км континуум,
        для тупого тела Cd ~ 0.9-1.2. Держим константу 1.0: в свободно-
        молекулярной зоне торможение всё равно пренебрежимо (D/m ~ 0.01 м/с^2
        против g*sin(gamma) ~ 0.25 м/с^2), а вся динамика идёт в континууме.

    A:  площадь миделя корпуса спутника 150-200 кг — 0.6-1.0 м^2.
        Неустранимый фактор ~2 в beta = m/(Cd*A) без знания конкретного аппарата.
        beta двигает ВЫСОТУ пика: h* ~ H*ln(beta), удвоение beta опускает
        пик на H*ln2 ~ 5 км. Для гистограммы по слоям это эффект первого порядка.
    """

    mass: float = 175.0          # кг, полная масса объекта (диапазон ТЗ 150-200)
    area: float = 1.0            # м^2, площадь миделя
    Cd: float = 1.0              # безразмерный
    al_mass_fraction: float = 0.30   # массовая доля алюминия (Ferreira et al. 2024).
                                     # На шаге 1 не используется, задел для шага 5.
    nose_radius: float = 0.5     # м, эффективный радиус затупления.
                                 # Для кувыркающегося нерегулярного аппарата
                                 # физического Rn не существует — это подгоночный
                                 # параметр. Переход к средней по поверхности
                                 # величине через SHAPE_FACTOR_TUMBLING снимает
                                 # неловкость: главный параметр по массе
                                 # перестаёт быть неизмеримой величиной.
    wetted_area: float | None = None   # м^2, полная омываемая поверхность.
                                       # None -> 4*area (формула Коши), см. .wetted

    @property
    def ballistic_coefficient(self) -> float:
        """beta = m / (Cd * A), кг/м^2."""
        return self.mass / (self.Cd * self.area)

    @property
    def wetted(self) -> float:
        """Омываемая площадь, м^2. По умолчанию 4*area.

        Это НЕ подгонка. Формула Коши: для любого выпуклого тела средняя
        по случайным ориентациям площадь проекции равна 1/4 площади
        поверхности. Наш `area` для кувыркающегося тела и есть средняя
        проекция (её же используем в сопротивлении), значит

            A_омыв = 4 * area                                  ТОЧНО

        для любой выпуклой формы, не только для сферы. Задать вручную
        имеет смысл только для сильно невыпуклых тел (раскрытые панели).
        """
        return 4.0 * self.area if self.wetted_area is None else self.wetted_area

    @classmethod
    def plate(cls, mass: float, thickness: float, Cd: float = 1.5,
              rho_material: float = 2700.0, nose_floor: float = 5.0e-3, **kw):
        """Тонкая пластина — панель, кожух, элемент MLI.

        ПОЧЕМУ ОТДЕЛЬНЫЙ КОНСТРУКТОР. Выводить Rn из площади как у сферы
        (Rn = sqrt(A/pi)) для пластины неверно и даёт абсурд: панель с
        beta = 4 кг/м^2 получила бы Rn = 96 см. Пластина имеет низкий beta
        не потому, что она большая, а потому, что она ТОНКАЯ.

        Для кувыркающейся пластины по формуле Коши средняя проекция равна
        четверти поверхности, а поверхность ~ 2*A_пластины, значит средняя
        проекция = A/2. Отсюда

            beta = m/(Cd*A_проекц) = rho*A*t/(Cd*A/2) = 2*rho*t/Cd

        то есть beta задаётся ТОЛЩИНОЙ и ничем больше. Для Al при Cd=1.5:
        t = 1 мм -> beta = 3.6;  t = 2 мм -> beta = 7.2;  t = 5 мм -> 18.
        Это ровно та полоса 1-10, которую дают панели и MLI в списках
        фрагментов, — то есть параметризация через толщину воспроизводит
        известный диапазон, а не подгоняется под него.

        Эффективный радиус затупления — радиус кромки, ~t/2, НО с полом.
        Пол обязателен: при Rn -> 0 корреляция даёт q -> бесконечность,
        что нефизично. Реальная абляционная кромка сама себя затупляет до
        самосогласованного радиуса. Пол 5 мм — оценка снизу этого радиуса,
        и он входит в свип чувствительности.
        """
        area_plate = mass / (rho_material * thickness)
        area_proj = area_plate / 2.0
        return cls(mass=mass, area=area_proj, Cd=Cd,
                   nose_radius=max(thickness / 2.0, nose_floor),
                   wetted_area=2.0 * area_plate, **kw)

    @classmethod
    def compact(cls, mass: float, beta: float, Cd: float = 1.5, **kw):
        """Компактный (не пластинчатый) фрагмент: силовой набор, кронштейны.

        Здесь сфероэквивалент уместен: Rn = sqrt(A_проекц/pi).
        """
        area = mass / (Cd * beta)
        return cls(mass=mass, area=area, Cd=Cd,
                   nose_radius=float(np.sqrt(area / np.pi)), **kw)

    @classmethod
    def geometric_family(cls, scale: float, mass0: float = 175.0,
                         area0: float = 1.0, nose0: float = 0.5,
                         Cd: float = 1.5, **kw):
        """Геометрически подобное тело с линейным масштабом `scale`.

        m ~ L^3, A ~ L^2, Rn ~ L. Нужно, чтобы свипировать РАЗМЕР честно:
        свипировать один только Rn при фиксированной массе и площади —
        физически бессмысленно, и именно там прячется ошибка знака.
        """
        return cls(mass=mass0 * scale ** 3, area=area0 * scale ** 2,
                   nose_radius=nose0 * scale, Cd=Cd, **kw)


@dataclass
class EntryState:
    """Начальные условия входа.

    gamma0 — угол наклона траектории к МЕСТНОМУ ГОРИЗОНТУ, положительный вверх.
    При спуске отрицательный. Задаётся в градусах, внутри переводится в радианы.

    Диапазон -1...-3 град из ТЗ — это не "плюс-минус чуть-чуть", а разные
    режимы: на 120 км круговая скорость 7836 м/с против входных 7500, то есть
    центробежный и гравитационный члены в dgamma/dt почти сокращаются, и gamma
    успевает измениться вдвое за полёт.
    """

    altitude: float = 120.0e3    # м
    velocity: float = 7500.0     # м/с (относительно невращающейся Земли)
    gamma_deg: float = -1.5      # градусы
    inclination_deg: float = 53.0    # наклонение орбиты, град

    @property
    def corotation_speed(self) -> float:
        """Скорость соатмосферного вращения ВДОЛЬ ТРАЕКТОРИИ, м/с.

        Атмосфера вращается вместе с Землёй на восток со скоростью
        u = omega*R*cos(lat). Вдоль трассы работает её проекция u*sin(A),
        где A — путевой угол (азимут от севера). Из сферической тригонометрии
        для орбиты наклонения i:  sin(A) = cos(i)/cos(lat).

        Широта сокращается:

            v_вдоль = omega*R*cos(lat) * cos(i)/cos(lat) = omega*R*cos(i)

        То есть вклад зависит ТОЛЬКО от наклонения, а не от того, где
        именно объект входит. Проверка предельных случаев:
          i = 0    экваториальная прямая  -> +465 м/с (атмосфера догоняет)
          i = 53   типичная НОО           -> +280 м/с
          i = 90   полярная               -> 0
          i = 98   ССО, обратная          -> -65 м/с (атмосфера навстречу)
        """
        return OMEGA_EARTH * R_EARTH * np.cos(np.deg2rad(self.inclination_deg))

    @property
    def gamma_rad(self) -> float:
        return np.deg2rad(self.gamma_deg)

    def to_vector(self) -> np.ndarray:
        """Вектор состояния [V, gamma, h, s]."""
        return np.array([self.velocity, self.gamma_rad, self.altitude, 0.0])
